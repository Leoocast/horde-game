const translations: Record<AppLanguage, Record<TranslationKey, string>> = {
  en: english,
  es: spanish,
};

export function translate(language: AppLanguage, key: TranslationKey, params?: TranslationParams): string {
  const template = translations[language][key] ?? english[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match));
}

/** Test/audit surface: public copy must pass the same vocabulary guard as rendered card text. */
export function translationValues(language: AppLanguage): readonly string[] {
  return Object.values(translations[language]);
}

/** Runtime guard for declarative content that stores translation keys outside TypeScript. */
export function isTranslationKey(value: string): value is TranslationKey {
  return Object.prototype.hasOwnProperty.call(english, value);
}
