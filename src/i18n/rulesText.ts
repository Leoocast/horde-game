export function canonicalizeRulesText(text: string, language: AppLanguage): string {
  const replacements = language === "es" ? SPANISH_REPLACEMENTS : ENGLISH_REPLACEMENTS;
  return replacements.reduce((result, [pattern, replacement]) => result.replace(pattern, replacement), text);
}

